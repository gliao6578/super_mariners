from pathlib import Path
import ee
import pandas as pd
import numpy as np

#Earth Engine
ee.Authenticate()
ee.Initialize(project="mariner-radar-tracker")

PROJECT_ROOT = Path("/content/super_mariners-main")
ANOMALY_FILE = PROJECT_ROOT / "data" / "processed" / "san_diego_categorized_anomalies.csv"
CLEAN_AIS_FILE = PROJECT_ROOT / "data" / "processed" / "san_diego_ais_cleaned.csv"
OUT_SAR_FILE = PROJECT_ROOT / "data" / "processed" / "san_diego_sar_confirmed_anomalies.csv"

# 2. Load Flagged Anomalous MMSIs
anom_df = pd.read_csv(ANOMALY_FILE)
flagged_ships = anom_df[anom_df["is_anomalous"] == True].copy()
flagged_mmsis = set(flagged_ships["mmsi"].unique())
print(f"Loaded {len(flagged_mmsis):,} anomalous vessels to cross-check against Sentinel-1 SAR.")

# 3. Query Sentinel-1 Overpass Scenes Over San Diego (4-Month Window)
san_diego_roi = ee.Geometry.Rectangle([-117.65, 32.50, -117.05, 32.95])

s1_col = (
    ee.ImageCollection("COPERNICUS/S1_GRD")
    .filterBounds(san_diego_roi)
    .filterDate("2020-01-01", "2020-05-01")  # Covers full Jan-Apr 2020 window
    .filter(ee.Filter.eq("instrumentMode", "IW"))
    .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VV"))
    .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VH"))
    .select(["VV", "VH"])
)

# Extract scene IDs and exact UTC acquisition timestamps
scene_info = s1_col.aggregate_array("system:index").getInfo()
scene_times = s1_col.aggregate_array("system:time_start").getInfo()

scenes_df = pd.DataFrame({
    "scene_id": scene_info,
    "overpass_time": pd.to_datetime(scene_times, unit="ms", utc=True)
}).sort_values("overpass_time")

print(f"Found {len(scenes_df)} Sentinel-1 radar overpasses over San Diego in Jan–Apr 2020.\n")

# 4. Load Cleaned AIS Pings for Flagged Ships & Match to Overpass Timestamps (+/- 15 min)
ais_chunks = []
for chunk in pd.read_csv(CLEAN_AIS_FILE, usecols=["mmsi", "base_date_time", "latitude", "longitude", "sog"], chunksize=500_000):
    sub = chunk[chunk["mmsi"].isin(flagged_mmsis)].copy()
    if not sub.empty:
        ais_chunks.append(sub)

flagged_pings = pd.concat(ais_chunks, ignore_index=True)
flagged_pings["base_date_time"] = pd.to_datetime(flagged_pings["base_date_time"], errors="coerce", utc=True)
flagged_pings = flagged_pings.dropna(subset=["base_date_time", "latitude", "longitude"]).sort_values("base_date_time")

# Nearest-time join within +/- 15 minutes of a satellite pass
matched = pd.merge_asof(
    flagged_pings,
    scenes_df,
    left_on="base_date_time",
    right_on="overpass_time",
    direction="nearest",
    tolerance=pd.Timedelta("15min")
).dropna(subset=["scene_id"])

# Keep closest single ping per ship per satellite overpass
matched["time_offset_min"] = (matched["base_date_time"] - matched["overpass_time"]).abs().dt.total_seconds() / 60
matched = matched.sort_values("time_offset_min").drop_duplicates(subset=["mmsi", "scene_id"])

print(f"Matched {len(matched):,} anomalous ship observations within +/- 15 min of a SAR overpass.")

# 5. Extract Peak Radar Backscatter (VV & VH dB) in 50m Radius Around Each Ship
sar_results = []

for scene_id, group in matched.groupby("scene_id"):
    img = ee.Image(f"COPERNICUS/S1_GRD/{scene_id}").select(["VV", "VH"])

    # Build Earth Engine FeatureCollection of 50m buffers around matched AIS coordinates
    features = []
    for idx, row in group.iterrows():
        pt = ee.Geometry.Point([row["longitude"], row["latitude"]]).buffer(50)
        features.append(ee.Feature(pt, {"row_idx": int(idx), "mmsi": int(row["mmsi"])}))

    fc = ee.FeatureCollection(features)
    sampled = img.reduceRegions(collection=fc, reducer=ee.Reducer.max(), scale=10).getInfo()

    for feat in sampled["features"]:
        props = feat["properties"]
        sar_results.append({
            "row_idx": props["row_idx"],
            "sar_max_vv_db": props.get("VV"),
            "sar_max_vh_db": props.get("VH"),
        })

if sar_results:
    sar_df = pd.DataFrame(sar_results).set_index("row_idx")
    matched = matched.join(sar_df)

    # Classify SAR physical confirmation
    def evaluate_sar(row):
        vv = row["sar_max_vv_db"]
        if pd.isna(vv):
            return "Outside SAR Swath Edge"
        elif vv > -10.0:
            return "SAR Confirmed: Strong Metallic Target"
        elif vv > -14.0:
            return "SAR Partial: Small/Weak Target"
        else:
            return "SAR Unconfirmed: No Radar Return (Possible Spoof/Small Craft)"

    matched["sar_verification_status"] = matched.apply(evaluate_sar, axis=1)

    # Merge back with the Random Forest anomaly category labels
    final_sar_report = matched.merge(
        flagged_ships[["mmsi", "vessel_group", "predicted_behavior_class", "reported_class_probability", "anomaly_category"]],
        on="mmsi",
        how="left"
    )

    print("\n--- SAR VERIFICATION SUMMARY FOR ANOMALOUS VESSELS ---")
    print(final_sar_report["sar_verification_status"].value_counts().to_string())

    print("\n--- SAMPLE SAR-CONFIRMED ANOMALIES ---")
    cols = ["mmsi", "vessel_group", "anomaly_category", "overpass_time", "sar_max_vv_db", "sar_verification_status"]
    print(final_sar_report[cols].head(15).to_string(index=False))

    final_sar_report.to_csv(OUT_SAR_FILE, index=False)
    print(f"\nSaved SAR verification report to: {OUT_SAR_FILE}")
else:
    print("No flagged AIS pings fell within +/- 15 minutes of a Sentinel-1 overpass.")

