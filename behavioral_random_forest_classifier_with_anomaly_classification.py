ANOMALY_FILE = PROJECT_ROOT / "data" / "processed" / "san_diego_categorized_anomalies.csv"
OUT_HTML_FILE = PROJECT_ROOT / "data" / "processed" / "san_diego_3month_grid_map.html"

#Load Vessel Classifications & Anomaly Labels
vessel_meta = pd.read_csv(ANOMALY_FILE)[
    ["mmsi", "vessel_group", "anomaly_category", "is_anomalous", "reported_class_probability"]
]

#Load Cleaned GPS Pings & Merge Labels
use_cols = ["mmsi", "base_date_time", "latitude", "longitude", "sog"]
df = pd.read_csv(CLEAN_AIS_FILE, usecols=use_cols, low_memory=False)
df["base_date_time"] = pd.to_datetime(df["base_date_time"], errors="coerce", utc=True)
df = df.dropna(subset=["mmsi", "base_date_time", "latitude", "longitude"])
df = df.merge(vessel_meta, on="mmsi", how="inner")

# Resample to 15-min intervals for smooth rendering
df = df.sort_values(["mmsi", "base_date_time"]).reset_index(drop=True)
df["time_bin"] = df["base_date_time"].dt.floor("15min")
df = df.drop_duplicates(subset=["mmsi", "time_bin"]).copy()

# Split trips if a ship disappears for > 6 hours
df["time_gap_hr"] = df.groupby("mmsi")["base_date_time"].diff().dt.total_seconds() / 3600
df["trip_id"] = (df["time_gap_hr"] > 6).groupby(df["mmsi"]).cumsum()
df["month_num"] = df["base_date_time"].dt.month

#Ship-Type Colors
COLOR_MAP = {
    "Cargo": "#0052cc",                  # Deep Royal Blue
    "Tanker": "#d90429",                 # Crimson Red
    "Passenger": "#1b9e3e",              # Forest Green
    "Fishing": "#e67e00",                # Dark Orange
    "Tug Tow": "#7b2cbf",                # Deep Purple
    "Military": "#008080",               # Teal
    "Pleasure Craft/Sailing": "#d63384", # Magenta Pink
}

MONTH_NAMES = {
    1: "January 2020",
    2: "February 2020",
    3: "March 2020",
}

def build_month_map(month_df, month_title):
    m = folium.Map(location=[32.68, -117.24], zoom_start=11, tiles="Esri.WorldStreetMap")

    # San Diego Bounding Box
    folium.Rectangle(
        bounds=[[32.50, -117.65], [32.95, -117.05]],
        color="#334155",
        weight=1.5,
        fill=False,
        dash_array="5, 5",
        tooltip="San Diego AIS Study Bounding Box"
    ).add_to(m)

    # Month Title
    title_html = f"""
    <div style="position: fixed; top: 10px; left: 50px; z-index: 9999;
                background: rgba(15, 23, 42, 0.92); color: white; padding: 7px 14px;
                border-radius: 6px; font-family: sans-serif; font-size: 14px;
                font-weight: bold; box-shadow: 0 2px 6px rgba(0,0,0,0.3);">
        {month_title} ({month_df['mmsi'].nunique():,} Ships)
    </div>
    """
    m.get_root().html.add_child(folium.Element(title_html))

    layers = {}
    for v_type, color in COLOR_MAP.items():
        fg = folium.FeatureGroup(name=f"<span style='color:{color};'>&#9632;</span> {v_type}")
        fg.add_to(m)
        layers[v_type] = fg

    for (mmsi, trip_id), group in month_df.groupby(["mmsi", "trip_id"]):
        if len(group) < 2:
            continue

        v_type = next(iter(group["vessel_group"]))
        color = COLOR_MAP.get(v_type, "#555555")
        is_anom = bool(next(iter(group["is_anomalous"])))
        anom_label = next(iter(group["anomaly_category"]))
        coords = list(zip(group["latitude"], group["longitude"]))

        popup_html = (
            f"<b>MMSI:</b> {mmsi}<br>"
            f"<b>Ship Type:</b> {v_type}<br>"
            f"<b>Status:</b> {anom_label}<br>"
            f"<b>GPS Pings:</b> {len(group)}<br>"
            f"<b>Start:</b> {group['base_date_time'].min().strftime('%Y-%m-%d %H:%M UTC')}<br>"
            f"<b>End:</b> {group['base_date_time'].max().strftime('%Y-%m-%d %H:%M UTC')}"
        )

        line = folium.PolyLine(
            locations=coords,
            color=color,
            weight=3.4 if is_anom else 1.6,
            opacity=0.95 if is_anom else 0.50,
            dash_array="8, 6" if is_anom else None,
            popup=folium.Popup(popup_html, max_width=260),
            tooltip=f"{'[ANOMALY] ' if is_anom else ''}{v_type} | MMSI: {mmsi}"
        )
        line.add_to(layers[v_type])

        PolyLineTextPath(
            line,
            "   >   ",
            repeat=True,
            offset=4,
            attributes={"fill": color, "font-weight": "bold", "font-size": "12"}
        ).add_to(layers[v_type])

        folium.CircleMarker(
            location=coords[-1],
            radius=3.8 if is_anom else 2.2,
            color=color,
            fill=True,
            fill_color="white" if is_anom else color,
            fill_opacity=0.95,
            tooltip=f"End Ping | MMSI: {mmsi}"
        ).add_to(layers[v_type])

    folium.LayerControl(collapsed=True).add_to(m)
    return m._repr_html_()

